/** Контакты компании из настроек: по ним отправляют обращения по данным. Пустые контакты не выдаём за настоящие. */
async function OperatorContacts() {
  const { settings } = await getShopData();
  const links = contactLinks(settings.company.contacts);
  if (!links.length) {
    return (
      <p className="rounded-field border border-ply bg-surface-2 px-4 py-3 text-[0.9375rem]">
        Контакты компании ещё не указаны владельцем. Укажите их в кабинете, раздел «Компания»: по ним клиенты будут направлять обращения.
      </p>
    );
  }
  return (
    <ul className="flex flex-wrap gap-x-5">
      {links.map((c) => (
        <li key={c.kind}>
          <a href={c.href} className="inline-flex min-h-11 items-center">
            <span className="text-muted">{c.label}:</span>
            <span className={`ml-1.5 font-medium tabular-nums ${linkClass}`}>{c.text}</span>
          </a>
        </li>
      ))}
    </ul>
  );
}
